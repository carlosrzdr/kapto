//! TypeScript types for the web UI, generated from the API's OpenAPI
//! document, so the UI can't disagree with the API it was built against.
//!
//! Handles the shapes the API uses: objects with required and optional
//! fields, arrays, strings, integers, numbers, booleans, nullable values,
//! string enums (as unions of their values; one that may grow,
//! `x-extensible-enum`, also as any other string), objects inside another
//! schema (as object types), `oneOf` choices between those (as unions, so a
//! choice tagged by a field narrows on it), `allOf` of other schemas and
//! fields (a struct flattening another, as an interface extending it) and
//! references to other schemas. Anything else becomes `unknown`, which the
//! UI's type check then refuses to use without a look.

use std::fmt::Write as _;

use serde_json::Value;

/// The first line of the generated file.
pub(crate) const HEADER: &str = "// Generated by `cargo xtask gen` from the API's OpenAPI document. Edit the API, not this file.\n\n";

/// The UI's types for every schema in `document`, and the API version.
pub(crate) fn api_types(document: &Value, api_version: u32) -> String {
    let mut out = String::from(HEADER);
    let _ = writeln!(
        out,
        "/** The API version these types describe; the UI refuses any other. */\nexport const API_VERSION = {api_version};"
    );
    let schemas = document["components"]["schemas"].as_object();
    let mut names: Vec<&String> = schemas.into_iter().flat_map(|s| s.keys()).collect();
    names.sort();
    for name in names {
        let schema = &document["components"]["schemas"][name.as_str()];
        out.push('\n');
        comment(&mut out, schema, "");
        let (extends, own) = match flattened(schema) {
            Some(parts) => parts,
            None if schema["properties"].is_null() && schema["type"] != "object" => {
                let _ = writeln!(out, "export type {name} = {};", type_of(schema));
                continue;
            }
            None => (Vec::new(), vec![schema]),
        };
        if extends.is_empty() {
            let _ = writeln!(out, "export interface {name} {{");
        } else {
            let _ = writeln!(
                out,
                "export interface {name} extends {} {{",
                extends.join(", ")
            );
        }
        let required: Vec<&str> = own
            .iter()
            .flat_map(|part| part["required"].as_array().into_iter().flatten())
            .filter_map(Value::as_str)
            .collect();
        let mut fields: Vec<(&String, &Value)> = own
            .iter()
            .flat_map(|part| part["properties"].as_object().into_iter().flatten())
            .collect();
        fields.sort_by_key(|(field, _)| *field);
        for (field, property) in fields {
            comment(&mut out, property, "  ");
            let optional = if required.contains(&field.as_str()) {
                ""
            } else {
                "?"
            };
            let _ = writeln!(out, "  {field}{optional}: {};", type_of(property));
        }
        out.push_str("}\n");
    }
    out
}

/// An `allOf` schema's parts: the schemas it takes every field of, by
/// name, and the objects listing fields of its own; `None` if it isn't one,
/// or has a part of another shape.
fn flattened(schema: &Value) -> Option<(Vec<String>, Vec<&Value>)> {
    let parts = schema["allOf"]
        .as_array()
        .filter(|parts| !parts.is_empty())?;
    let mut extends = Vec::new();
    let mut own = Vec::new();
    for part in parts {
        if let Some(reference) = part["$ref"].as_str() {
            extends.push(reference.rsplit('/').next()?.to_owned());
        } else if part["type"] == "object" && part["properties"].is_object() {
            own.push(part);
        } else {
            return None;
        }
    }
    Some((extends, own))
}

/// A property's or item's TypeScript type.
fn type_of(schema: &Value) -> String {
    if let Some(reference) = schema["$ref"].as_str() {
        return reference.rsplit('/').next().unwrap_or("unknown").to_owned();
    }
    if let Some(choices) = schema["oneOf"].as_array()
        && !choices.is_empty()
    {
        let types: Vec<String> = choices.iter().map(type_of).collect();
        if types.iter().all(|kind| kind != "unknown") {
            return types.join(" | ");
        }
        return "unknown".to_owned();
    }
    if let Some(values) = schema["enum"].as_array()
        && let Some(values) = values
            .iter()
            .map(|value| value.as_str().map(|value| format!("{value:?}")))
            .collect::<Option<Vec<_>>>()
    {
        return values.join(" | ");
    }
    // Values added later are other strings, which the UI must allow for.
    if let Some(values) = schema["x-extensible-enum"].as_array()
        && let Some(values) = values
            .iter()
            .map(|value| value.as_str().map(|value| format!("{value:?}")))
            .collect::<Option<Vec<_>>>()
    {
        return format!("{} | (string & {{}})", values.join(" | "));
    }
    let kinds: Vec<&str> = match &schema["type"] {
        Value::String(kind) => vec![kind.as_str()],
        Value::Array(kinds) => kinds.iter().filter_map(Value::as_str).collect(),
        _ => Vec::new(),
    };
    if kinds.is_empty() {
        return "unknown".to_owned();
    }
    if kinds == ["object"] {
        return object_of(schema).unwrap_or_else(|| "unknown".to_owned());
    }
    let types: Vec<String> = kinds
        .into_iter()
        .map(|kind| match kind {
            "string" => "string".to_owned(),
            "integer" | "number" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "null" => "null".to_owned(),
            "array" => {
                let item = type_of(&schema["items"]);
                if item.contains(' ') {
                    format!("({item})[]")
                } else {
                    format!("{item}[]")
                }
            }
            _ => "unknown".to_owned(),
        })
        .collect();
    types.join(" | ")
}

/// An object schema inside another as a TypeScript object type, its fields
/// in name order; `None` if it lists no fields.
fn object_of(schema: &Value) -> Option<String> {
    let required: Vec<&str> = schema["required"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect();
    let mut fields: Vec<(&String, &Value)> = schema["properties"].as_object()?.iter().collect();
    if fields.is_empty() {
        return None;
    }
    fields.sort_by_key(|(field, _)| *field);
    let fields: Vec<String> = fields
        .into_iter()
        .map(|(field, property)| {
            let optional = if required.contains(&field.as_str()) {
                ""
            } else {
                "?"
            };
            format!("{field}{optional}: {}", type_of(property))
        })
        .collect();
    Some(format!("{{ {} }}", fields.join("; ")))
}

/// The schema's description as a doc comment, if it has one.
fn comment(out: &mut String, schema: &Value, indent: &str) {
    // An optional reference carries its description inside its `oneOf`.
    let description = schema["description"].as_str().or_else(|| {
        schema["oneOf"]
            .as_array()?
            .iter()
            .find_map(|choice| choice["description"].as_str())
    });
    let Some(description) = description else {
        return;
    };
    let lines: Vec<&str> = description.lines().collect();
    if let [line] = lines.as_slice() {
        let _ = writeln!(out, "{indent}/** {line} */");
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in lines {
        let _ = writeln!(out, "{indent} * {line}");
    }
    let _ = writeln!(out, "{indent} */");
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn objects_become_interfaces_with_optional_nullable_and_referenced_fields() {
        let document = json!({"components": {"schemas": {
            "Status": {
                "type": "object",
                "description": "What it is doing.",
                "required": ["streams", "viewer"],
                "properties": {
                    "episode": {"type": ["string", "null"], "description": "The episode,\nif any."},
                    "streams": {"type": "array", "items": {"$ref": "#/components/schemas/Stream"}},
                    "viewer": {"$ref": "#/components/schemas/Viewer"},
                    "codes": {"type": "array", "items": {"type": ["integer", "null"]}}
                }
            }
        }}});
        assert_eq!(
            api_types(&document, 1),
            format!(
                "{HEADER}/** The API version these types describe; the UI refuses any other. */\n\
                 export const API_VERSION = 1;\n\
                 \n\
                 /** What it is doing. */\n\
                 export interface Status {{\n  \
                   codes?: (number | null)[];\n  \
                   /**\n   \
                    * The episode,\n   \
                    * if any.\n   \
                    */\n  \
                   episode?: string | null;\n  \
                   streams: Stream[];\n  \
                   viewer: Viewer;\n\
                 }}\n"
            )
        );
    }

    #[test]
    fn a_string_enum_becomes_a_union_of_its_values() {
        let document = json!({"components": {"schemas": {
            "Kind": {"type": "string", "enum": ["status", "episode_started"], "description": "Which."}
        }}});
        assert!(
            api_types(&document, 1)
                .ends_with("/** Which. */\nexport type Kind = \"status\" | \"episode_started\";\n")
        );
    }

    #[test]
    fn a_string_enum_that_may_grow_is_its_values_or_any_other_string() {
        let document = json!({"components": {"schemas": {
            "Kind": {"type": "string", "x-extensible-enum": ["status", "episode_started"], "description": "Which."}
        }}});
        assert!(api_types(&document, 1).ends_with(
            "/** Which. */\nexport type Kind = \"status\" | \"episode_started\" | (string & {});\n"
        ));
    }

    #[test]
    fn an_optional_reference_is_its_type_or_null_with_its_description() {
        let property = json!({"oneOf": [
            {"type": "null"},
            {"$ref": "#/components/schemas/Status", "description": "What it does."}
        ]});
        assert_eq!(type_of(&property), "null | Status");
        let mut out = String::new();
        comment(&mut out, &property, "  ");
        assert_eq!(out, "  /** What it does. */\n");
    }

    #[test]
    fn a_choice_tagged_by_a_field_becomes_a_union_of_object_types() {
        let shape = json!({"oneOf": [
            {"type": "object", "required": ["kind", "size"], "properties": {
                "kind": {"type": "string", "enum": ["box"]},
                "size": {"type": "array", "items": {"type": "number"}}
            }},
            {"type": "object", "required": ["kind"], "properties": {
                "kind": {"type": "string", "enum": ["sphere"]},
                "radius": {"type": "number"}
            }}
        ]});
        assert_eq!(
            type_of(&shape),
            "{ kind: \"box\"; size: number[] } | { kind: \"sphere\"; radius?: number }"
        );
    }

    #[test]
    fn a_struct_flattening_another_becomes_an_interface_extending_it() {
        let document = json!({"components": {"schemas": {
            "Counted": {"description": "How it went.", "allOf": [
                {"$ref": "#/components/schemas/Named", "description": "Which."},
                {"type": "object", "required": ["sent"], "properties": {
                    "sent": {"type": "integer", "description": "Bytes sent."},
                    "left": {"type": "integer"}
                }}
            ]}
        }}});
        assert!(api_types(&document, 1).ends_with(
            "/** How it went. */\n\
             export interface Counted extends Named {\n  \
               left?: number;\n  \
               /** Bytes sent. */\n  \
               sent: number;\n\
             }\n"
        ));
        assert_eq!(
            flattened(&json!({"allOf": [{"type": "string"}]})),
            None,
            "a part neither a reference nor an object with fields isn't flattened"
        );
    }

    #[test]
    fn a_shape_the_generator_doesnt_know_becomes_unknown() {
        assert_eq!(type_of(&json!({"oneOf": []})), "unknown");
        assert_eq!(
            type_of(&json!({"oneOf": [{"type": "string"}, {"type": "object"}]})),
            "unknown"
        );
        assert_eq!(type_of(&json!({"type": "object"})), "unknown");
    }
}
